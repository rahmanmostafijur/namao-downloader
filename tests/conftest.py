            "-filter_complex", "[0:v]split=2[a][b];[b]scale=320:180[c]",
            "-map", "[a]", "-map", "[c]", "-map", "1:a",
            "-c:v", "libx264", "-preset", "ultrafast", "-g", "25", "-keyint_min", "25",
