HAS_FFMPEG = bool(shutil.which("ffmpeg") and shutil.which("ffprobe"))
requires_ffmpeg = pytest.mark.skipif(not HAS_FFMPEG, reason="ffmpeg/ffprobe not installed")

SLOW_SEGMENT_DELAY = 0.6


class _Handler(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *args):  # keep test output quiet
        pass

    def do_GET(self):  # noqa: N802
        path = self.path
        if path.startswith("/gone/"):
            self.send_error(404)
            return
        if path.startswith("/broken/"):
            if path.endswith(".m4s"):
                self.send_error(404)
                return
            self.path = path[len("/broken"):]
        if path.startswith("/slow/"):
            self.path = path[len("/slow"):]
            if self.path.endswith(".m4s"):
                time.sleep(SLOW_SEGMENT_DELAY)
        super().do_GET()


class _DualStackServer(http.server.ThreadingHTTPServer):
    """Listen on IPv4 and IPv6: `localhost` resolves to ::1 first on many hosts and a
    refused/timed-out IPv6 attempt would otherwise add seconds to every request."""

    address_family = socket.AF_INET6

    def server_bind(self):
        self.socket.setsockopt(socket.IPPROTO_IPV6, socket.IPV6_V6ONLY, 0)
        super().server_bind()


def _make_server(handler):
    try:
        return _DualStackServer(("::", 0), handler)
    except OSError:  # no IPv6 on this host
        return http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)


